import Foundation

// The fixed bytes real cartridges carry. A file named like a game but missing
// its format's header is not one — such names turn up in test fixtures,
// emulator bundles and downloads. Formats with no fixed header pass: the
// folder fences keep non-game locations out instead.
public enum CartHeader {

    // The 48-byte logo every Game Boy / Game Boy Color cart carries at 0x104.
    public static let gameBoyLogo: [UInt8] = [
        0xCE, 0xED, 0x66, 0x66, 0xCC, 0x0D, 0x00, 0x0B, 0x03, 0x73, 0x00, 0x83,
        0x00, 0x0C, 0x00, 0x0D, 0x00, 0x08, 0x11, 0x1F, 0x88, 0x89, 0x00, 0x0E,
        0xDC, 0xCC, 0x6E, 0xE6, 0xDD, 0xDD, 0xD9, 0x99, 0xBB, 0xBB, 0x67, 0x63,
        0x6E, 0x0E, 0xEC, 0xCC, 0xDD, 0xDC, 0x99, 0x9F, 0xBB, 0xB9, 0x33, 0x3E,
    ]

    // The 156-byte logo every Game Boy Advance and Nintendo DS cart carries —
    // at 0x04 on GBA, 0xC0 on DS.
    public static let advanceLogo: [UInt8] = [
        0x24, 0xFF, 0xAE, 0x51, 0x69, 0x9A, 0xA2, 0x21, 0x3D, 0x84, 0x82, 0x0A,
        0x84, 0xE4, 0x09, 0xAD, 0x11, 0x24, 0x8B, 0x98, 0xC0, 0x81, 0x7F, 0x21,
        0xA3, 0x52, 0xBE, 0x19, 0x93, 0x09, 0xCE, 0x20, 0x10, 0x46, 0x4A, 0x4A,
        0xF8, 0x27, 0x31, 0xEC, 0x58, 0xC7, 0xE8, 0x33, 0x82, 0xE3, 0xCE, 0xBF,
        0x85, 0xF4, 0xDF, 0x94, 0xCE, 0x4B, 0x09, 0xC1, 0x94, 0x56, 0x8A, 0xC0,
        0x13, 0x72, 0xA7, 0xFC, 0x9F, 0x84, 0x4D, 0x73, 0xA3, 0xCA, 0x9A, 0x61,
        0x58, 0x97, 0xA3, 0x27, 0xFC, 0x03, 0x98, 0x76, 0x23, 0x1D, 0xC7, 0x61,
        0x03, 0x04, 0xAE, 0x56, 0xBF, 0x38, 0x84, 0x00, 0x40, 0xA7, 0x0E, 0xFD,
        0xFF, 0x52, 0xFE, 0x03, 0x6F, 0x95, 0x30, 0xF1, 0x97, 0xFB, 0xC0, 0x85,
        0x60, 0xD6, 0x80, 0x25, 0xA9, 0x63, 0xBE, 0x03, 0x01, 0x4E, 0x38, 0xE2,
        0xF9, 0xA2, 0x34, 0xFF, 0xBB, 0x3E, 0x03, 0x44, 0x78, 0x00, 0x90, 0xCB,
        0x88, 0x11, 0x3A, 0x94, 0x65, 0xC0, 0x7C, 0x63, 0x87, 0xF0, 0x3C, 0xAF,
        0xD6, 0x25, 0xE4, 0x8B, 0x38, 0x0A, 0xAC, 0x72, 0x21, 0xD4, 0xF8, 0x07,
    ]

    /// Whether `file` could be a game of `ext`'s format, judged by the bytes
    /// every real copy of it carries. Each check is one small read.
    public static func plausible(_ file: URL, ext: String) -> Bool {
        switch ext {
        case "gb", "gbc":
            return bytes(file, at: 0x104, count: gameBoyLogo.count) == gameBoyLogo
        case "gba":
            return bytes(file, at: 0x04, count: advanceLogo.count) == advanceLogo
        case "nds":
            return bytes(file, at: 0xC0, count: advanceLogo.count) == advanceLogo
        case "nes":
            return bytes(file, at: 0, count: 4) == [0x4E, 0x45, 0x53, 0x1A]
        case "n64", "z64", "v64":
            return [[UInt8(0x80), 0x37, 0x12, 0x40], [0x37, 0x80, 0x40, 0x12], [0x40, 0x12, 0x37, 0x80]]
                .contains(bytes(file, at: 0, count: 4) ?? [])
        case "chd":
            return bytes(file, at: 0, count: 8) == Array("MComprHD".utf8)
        case "pbp":
            return bytes(file, at: 0, count: 4) == [0x00, 0x50, 0x42, 0x50]
        case "cue":
            // A sheet naming no track cannot play.
            return !Playlist.cue(file).isEmpty
        default:
            return true
        }
    }

    static func bytes(_ file: URL, at offset: UInt64, count: Int) -> [UInt8]? {
        guard let handle = try? FileHandle(forReadingFrom: file) else { return nil }
        defer { try? handle.close() }
        guard let _ = try? handle.seek(toOffset: offset),
              let data = try? handle.read(upToCount: count), data.count == count else { return nil }
        return [UInt8](data)
    }
}
